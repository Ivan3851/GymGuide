export function localizeRecord(record, locale, kind = 'catalog') {
  if (!record) return record
  const catalogKey = kind === 'equipment' ? `equipment:${record.slug}` : record.slug
  const demoTranslation = record.isDemo ? demoContent[catalogKey] : null
  const selectedLanguage = locale === 'mk-MK' ? 'mk-MK' : 'en'
  const fallbackLanguage = selectedLanguage === 'mk-MK' ? 'en' : 'mk-MK'
  const selected = record.translations?.[selectedLanguage]
  const fallback = record.translations?.[fallbackLanguage]
  const localized = {}
  for (const field of [
    'name',
    'description',
    'summary',
    'instructions',
    'benefits',
    'tips',
    'commonMistakes',
  ]) {
    const candidates = [selected?.[field], fallback?.[field]]
    if (locale === 'mk-MK') candidates.push(demoTranslation?.[field])
    candidates.push(record[field])
    const value = candidates.find((candidate) =>
      Array.isArray(candidate)
        ? candidate.length > 0
        : typeof candidate === 'string' && candidate.trim(),
    )
    if (value !== undefined) localized[field] = value
  }
  return { ...record, ...localized }
}

export function localizeRecords(records, locale, kind = 'catalog') {
  return Array.isArray(records)
    ? records.map((record) => localizeRecord(record, locale, kind))
    : records
}

export function localizeEquipmentUnit(unit, locale) {
  if (!unit) return unit
  const localizedType = unit.equipmentType
    ? localizeRecord(unit.equipmentType, locale, 'equipment')
    : null
  let result = localizedType
    ? { ...unit, equipmentType: localizedType, equipmentTypeName: localizedType.name }
    : unit
  if (locale === 'mk-MK' && unit.isDemo === true) {
    const equipment = localizedType || demoContent[`equipment:${unit.equipmentTypeId}`]
    if (equipment)
      result = {
        ...result,
        displayName: `Демо · ${equipment.name}`,
        equipmentTypeName: equipment.name,
      }
  }
  return result
}
